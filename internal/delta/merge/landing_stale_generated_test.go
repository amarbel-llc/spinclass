package merge

import (
	"bytes"
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"code.linenisgreat.com/crap/go-crap/v2/crap"
)

// preparePlainMerge is prepareRacedMerge without the race: one session commit
// writing file, pinned by PrepareMerge, and main left where it was.
func preparePlainMerge(t *testing.T, repoDir, wtPath, branch, file, content string) (pinnedSha string, rep *crap.Reporter, ts *crap.TestStream, buf *bytes.Buffer) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(wtPath, file), []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	runGit(t, wtPath, "add", file)
	runGit(t, wtPath, "commit", "-m", "session commit")
	buf = &bytes.Buffer{}
	rep = crap.NewReporter(buf, crap.ReporterOptions{})
	ts = rep.TestStream(0)
	var err error
	pinnedSha, err = PrepareMerge(context.Background(), ts, repoDir, wtPath, branch, "main", false, PostMergeOptions{})
	if err != nil {
		t.Fatalf("PrepareMerge: %v\n%s", err, buf.String())
	}
	return pinnedSha, rep, ts, buf
}

// A gate that fails after the landing rebased onto a moved tip may be failing
// on a generated file made against the old tip: the landing rebase re-runs
// neither the regenerate phase nor REPAIR (spinclass#470). The failure then
// carries a hint naming the generated files the landing touched and saying to
// re-merge, which rebases the session worktree and re-runs them there.
func TestFinishMergeHintsAtStaleGeneratedFilesAfterARebasedLanding(t *testing.T) {
	repoDir := setupRepo(t)
	wtPath := setupWorktree(t, repoDir, "feature-gen")
	writeRepoSweatfile(t, repoDir, "[hooks]\npre-merge = \"false\"\n")

	pinnedSha, _, rep, ts, buf := prepareRacedMerge(t, repoDir, wtPath, "feature-gen",
		"facade.go", "// Code generated by stubgen; DO NOT EDIT.\n\npackage facade\n",
		"source.go", "package source\n")

	_, err := FinishMerge(context.Background(), &mockExecutor{}, rep, ts,
		repoDir, wtPath, "feature-gen", "main", pinnedSha, false, true, nil, PostMergeOptions{})
	ts.Finish()
	if err == nil {
		t.Fatalf("FinishMerge succeeded with a failing gate\n%s", buf.String())
	}
	for _, want := range []string{"rebased onto moved main", "facade.go", "re-merge"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error %q lacks %q", err.Error(), want)
		}
		if !strings.Contains(buf.String(), want) {
			t.Errorf("result stream lacks %q:\n%s", want, buf.String())
		}
	}
	if strings.Contains(err.Error(), "source.go") {
		t.Errorf("error names source.go, which carries no generated-code marker: %q", err.Error())
	}
}

// Without a landing rebase there is no hint: a gate failure on an unmoved tip
// is the branch's own.
func TestFinishMergeGivesNoStaleHintWithoutALandingRebase(t *testing.T) {
	repoDir := setupRepo(t)
	wtPath := setupWorktree(t, repoDir, "feature-plain")
	writeRepoSweatfile(t, repoDir, "[hooks]\npre-merge = \"false\"\n")

	pinnedSha, rep, ts, buf := preparePlainMerge(t, repoDir, wtPath, "feature-plain",
		"facade.go", "// Code generated by stubgen; DO NOT EDIT.\n\npackage facade\n")

	_, err := FinishMerge(context.Background(), &mockExecutor{}, rep, ts,
		repoDir, wtPath, "feature-plain", "main", pinnedSha, false, true, nil, PostMergeOptions{})
	ts.Finish()
	if err == nil {
		t.Fatalf("FinishMerge succeeded with a failing gate\n%s", buf.String())
	}
	if strings.Contains(err.Error(), "re-merge") || strings.Contains(buf.String(), "may be stale") {
		t.Errorf("unexpected stale-generated hint without a landing rebase: %q\n%s", err.Error(), buf.String())
	}
}
