func TestEffectiveStandsAsideWithoutAPreCommitHook(t *testing.T) {
	pre := "conformist --staged"
	off := true
	withPre := sweatfile.Sweatfile{Hooks: &sweatfile.Hooks{PreCommit: &pre}}
	disabled := sweatfile.Sweatfile{Hooks: &sweatfile.Hooks{PreCommit: &pre, DisablePreCommit: &off}}

	if got := Effective(withPre, sweatfile.RepairGeneratedFail); got != sweatfile.RepairGeneratedFail {
		t.Errorf("with pre-commit: %q, want fail", got)
	}
	for name, sf := range map[string]sweatfile.Sweatfile{"none": {}, "disabled": disabled} {
		if got := Effective(sf, sweatfile.RepairGeneratedProtect); got != sweatfile.RepairGeneratedAllow {
			t.Errorf("pre-commit %s: %q, want allow (repair may be the generator)", name, got)
		}
	}
}
