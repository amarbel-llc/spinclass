const (
	generatorBytes = "// Code generated by stub. DO NOT EDIT.\n\npackage facade\n\nconst a = 1\nconst b = 2\n"
	formattedBytes = "// Code generated by stub. DO NOT EDIT.\n\npackage facade\n\nconst (\n\ta = 1\n\tb = 2\n)\n"
)

func gitIn(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", append([]string{"-C", dir}, args...)...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

func writeIn(t *testing.T, dir, name, body string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func readIn(t *testing.T, dir, name string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// newRepo: one commit holding a generated file and a hand-written one; the
// snapshot is that commit.
func newRepo(t *testing.T) (dir, snapshot string) {
	t.Helper()
	t.Setenv("GIT_AUTHOR_NAME", "t")
	t.Setenv("GIT_AUTHOR_EMAIL", "t@example.invalid")
	t.Setenv("GIT_COMMITTER_NAME", "t")
	t.Setenv("GIT_COMMITTER_EMAIL", "t@example.invalid")
	t.Setenv("GIT_CONFIG_GLOBAL", "/dev/null")
	t.Setenv("GIT_CONFIG_SYSTEM", "/dev/null")
	dir = t.TempDir()
	gitIn(t, dir, "init", "-q", "-b", "main")
	writeIn(t, dir, "base.txt", "base")
	gitIn(t, dir, "add", "base.txt")
	gitIn(t, dir, "commit", "-q", "-m", "base")
	writeIn(t, dir, "facade.go", generatorBytes)
	writeIn(t, dir, "main.go", "package main\nfunc main(){}\n")
	gitIn(t, dir, "add", "facade.go", "main.go")
	gitIn(t, dir, "commit", "-q", "-m", "work")
	return dir, gitIn(t, dir, "rev-parse", "HEAD")
}

func TestEnforceProtectRestoresAWorkingTreeEditToAGeneratedFile(t *testing.T) {
	dir, snap := newRepo(t)
	writeIn(t, dir, "facade.go", formattedBytes)
	writeIn(t, dir, "main.go", "package main\n\nfunc main() {}\n")

	kept, err := Enforce(dir, snap, sweatfile.RepairGeneratedProtect)
	if err != nil {
		t.Fatalf("Enforce: %v", err)
	}
	if !reflect.DeepEqual(kept, []string{"facade.go"}) {
		t.Errorf("kept = %v, want [facade.go]", kept)
	}
	if got := readIn(t, dir, "facade.go"); got != generatorBytes {
		t.Errorf("facade.go = %q, want the generator's bytes", got)
	}
	if got := readIn(t, dir, "main.go"); got != "package main\n\nfunc main() {}\n" {
		t.Errorf("repair's edit to a hand-written file was not kept: %q", got)
	}
	if st := gitIn(t, dir, "status", "--porcelain"); st != "M main.go" {
		t.Errorf("status = %q, want only main.go modified", st)
	}
}

func TestEnforceProtectFoldsTheRestoreIntoARepairAmend(t *testing.T) {
	dir, snap := newRepo(t)
	writeIn(t, dir, "facade.go", formattedBytes)
	writeIn(t, dir, "main.go", "package main\n\nfunc main() {}\n")
	gitIn(t, dir, "commit", "-q", "-a", "--amend", "--no-edit")

	kept, err := Enforce(dir, snap, sweatfile.RepairGeneratedProtect)
	if err != nil {
		t.Fatalf("Enforce: %v", err)
	}
	if !reflect.DeepEqual(kept, []string{"facade.go"}) {
		t.Errorf("kept = %v, want [facade.go]", kept)
	}
	if got := gitIn(t, dir, "show", "HEAD:facade.go"); got+"\n" != generatorBytes {
		t.Errorf("HEAD:facade.go = %q, want the generator's bytes", got)
	}
	if got := gitIn(t, dir, "show", "HEAD:main.go"); got != "package main\n\nfunc main() {}" {
		t.Errorf("the amend lost repair's edit to main.go: %q", got)
	}
	if got := gitIn(t, dir, "rev-parse", "HEAD~1"); got != gitIn(t, dir, "rev-parse", snap+"~1") {
		t.Errorf("the amend is not still an amend of the snapshot's commit")
	}
	if st := gitIn(t, dir, "status", "--porcelain"); st != "" {
		t.Errorf("tree not clean: %q", st)
	}
}

func TestEnforceProtectResetsHeadWhenTheAmendChangedOnlyGeneratedFiles(t *testing.T) {
	dir, snap := newRepo(t)
	writeIn(t, dir, "facade.go", formattedBytes)
	gitIn(t, dir, "commit", "-q", "-a", "--amend", "--no-edit")

	if _, err := Enforce(dir, snap, sweatfile.RepairGeneratedProtect); err != nil {
		t.Fatalf("Enforce: %v", err)
	}
	if got := gitIn(t, dir, "rev-parse", "HEAD"); got != snap {
		t.Errorf("HEAD = %s, want the snapshot %s (nothing but the generated file was amended)", got, snap)
	}
	if st := gitIn(t, dir, "status", "--porcelain"); st != "" {
		t.Errorf("tree not clean: %q", st)
	}
}

func TestEnforceProtectRestoresAGeneratedFileRepairDeleted(t *testing.T) {
	dir, snap := newRepo(t)
	gitIn(t, dir, "rm", "-q", "facade.go")

	kept, err := Enforce(dir, snap, sweatfile.RepairGeneratedProtect)
	if err != nil || !reflect.DeepEqual(kept, []string{"facade.go"}) {
		t.Fatalf("Enforce = %v, %v; want [facade.go]", kept, err)
	}
	if got := readIn(t, dir, "facade.go"); got != generatorBytes {
		t.Errorf("facade.go = %q, want it restored", got)
	}
}

func TestEnforceFailRefusesNamingThePath(t *testing.T) {
	dir, snap := newRepo(t)
	writeIn(t, dir, "facade.go", formattedBytes)

	kept, err := Enforce(dir, snap, sweatfile.RepairGeneratedFail)
	var refusal *RefusalError
	if !errors.As(err, &refusal) {
		t.Fatalf("err = %v, want a RefusalError", err)
	}
	if !reflect.DeepEqual(refusal.Paths, []string{"facade.go"}) || !strings.Contains(err.Error(), "facade.go") {
		t.Errorf("refusal = %v (%q), want it to name facade.go", refusal.Paths, err)
	}
	if kept != nil {
		t.Errorf("kept = %v, want nothing restored", kept)
	}
	if got := readIn(t, dir, "facade.go"); got != formattedBytes {
		t.Error("fail mode must leave the tree for the caller to undo")
	}
}

func TestEnforceAllowLeavesRepairsEdits(t *testing.T) {
	dir, snap := newRepo(t)
	writeIn(t, dir, "facade.go", formattedBytes)

	kept, err := Enforce(dir, snap, sweatfile.RepairGeneratedAllow)
	if err != nil || kept != nil {
		t.Fatalf("Enforce = %v, %v; want nothing", kept, err)
	}
	if got := readIn(t, dir, "facade.go"); got != formattedBytes {
		t.Errorf("allow undid repair's edit: %q", got)
	}
}

