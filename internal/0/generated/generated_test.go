package generated

import "testing"

func TestHasGoMarker(t *testing.T) {
	cases := []struct {
		name string
		src  string
		want bool
	}{
		{"marker before the package clause", "// Code generated by tommy. DO NOT EDIT.\n\npackage sweatfile\n", true},
		{"leading blank lines and other line comments first", "\n\n// Copyright the authors.\n//go:build linux\n\n// Code generated by dagnabit; DO NOT EDIT.\npackage facade\n", true},
		{"marker after the package clause", "package facade\n\n// Code generated by dagnabit. DO NOT EDIT.\n", false},
		{"wrong case", "// code generated by tommy. do not edit.\npackage x\n", false},
		{"missing DO NOT EDIT.", "// Code generated by tommy.\npackage x\n", false},
		{"DO NOT EDIT without the full stop", "// Code generated by tommy. DO NOT EDIT\npackage x\n", false},
		{"marker only inside a block comment", "/*\n// Code generated by tommy. DO NOT EDIT.\n*/\npackage x\n", false},
		{"marker as a one-line block comment", "/* Code generated by tommy. DO NOT EDIT. */\npackage x\n", false},
		{"indented marker", "  // Code generated by tommy. DO NOT EDIT.\npackage x\n", false},
		{"CRLF line endings", "// Code generated by tommy. DO NOT EDIT.\r\npackage x\r\n", true},
		{"marker alone, no newline", "// Code generated by tommy. DO NOT EDIT.", true},
		{"empty", "", false},
	}
	for _, c := range cases {
		if got := HasGoMarker([]byte(c.src)); got != c.want {
			t.Errorf("%s: HasGoMarker = %v, want %v", c.name, got, c.want)
		}
	}
}
